const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_BIN?{executablePath:process.env.CHROME_BIN}:{})});
 try{
  const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const origin=process.argv[2],url=origin+'/dashboard/';await page.goto(url);
  await page.waitForSelector('.card');
  const card=title=>page.locator('.card').filter({has:page.locator('.card-title',{hasText:new RegExp('^'+title+'$')})});
  await page.waitForFunction(()=>document.querySelectorAll('.card').length===13);
  await page.evaluate(()=>{window.savedGauge=document.querySelector('[data-card-type="gauge"]');});
  await page.waitForTimeout(600);
  assert(await page.evaluate(()=>window.savedGauge===document.querySelector('[data-card-type="gauge"]')),'Polling must retain gauge DOM');
  const before=await card('Gauge').boundingBox();
  await page.getByRole('button',{name:'Edit layout',exact:true}).click();
  const move=card('Gauge').getByRole('button',{name:'Move card',exact:true});
  await move.focus();await page.keyboard.press('ArrowDown');
  const moved=await card('Gauge').boundingBox();assert(moved.y>before.y,'Keyboard move should move a card');
  const resize=card('Gauge').getByRole('button',{name:'Resize card',exact:true});
  await resize.focus();await page.keyboard.press('ArrowRight');
  assert((await card('Gauge').boundingBox()).width>moved.width,'Keyboard resize should widen a card');
  const handle=await move.boundingBox();await page.mouse.move(handle.x+10,handle.y+8);await page.mouse.down();
  await page.mouse.move(handle.x+120,handle.y+122,{steps:5});await page.mouse.up();
  await page.waitForFunction(()=>document.getElementById('dashboardStatus').textContent.includes('Layout saved'));
  await page.getByRole('button',{name:'Lock layout',exact:true}).click();
  const saved=await page.request.get(origin+'/dashboard/cards.php?action=state').then(r=>r.json());
  const savedRect=JSON.stringify(saved.layout);
  await page.reload();await page.waitForSelector('.card');
  const restored=await page.request.get(origin+'/dashboard/cards.php?action=state').then(r=>r.json());
  assert.equal(JSON.stringify(restored.layout),savedRect);
  const second=await context.newPage();await second.goto(url);await second.waitForSelector('.card');
  assert.equal(await second.locator('[data-card-type="gauge"]').evaluate(e=>e.style.gridColumn),await card('Gauge').evaluate(e=>e.style.gridColumn));
  const range=card('Stepped').locator('[data-role="input"]'),number=card('Stepped').locator('[data-role="number"]');
  await number.fill('7');await number.press('Enter');await page.waitForTimeout(400);assert.equal(await range.inputValue(),'5');
  const hold=card('Hold').getByRole('button',{name:'Hold',exact:true});
  await hold.scrollIntoViewIfNeeded();const box=await hold.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
  await page.waitForTimeout(500);assert.equal(await hold.getAttribute('aria-pressed'),'true');
  await page.mouse.up();await page.waitForTimeout(300);assert.equal(await hold.getAttribute('aria-pressed'),'false');
  await hold.focus();await page.keyboard.down('Space');await page.waitForTimeout(250);
  assert.equal(await hold.getAttribute('aria-pressed'),'true');await page.keyboard.up('Space');
  await page.waitForTimeout(300);assert.equal(await hold.getAttribute('aria-pressed'),'false');
  // Legacy latch behavior stays available.
  const latch=card('Button').getByRole('button',{name:'Button',exact:true});await latch.click();await page.waitForTimeout(250);assert(await latch.isDisabled());
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download dashboard',exact:true}).click();
  const downloaded=await download;
  assert(downloaded.suggestedFilename().endsWith('.json'));
  page.on('dialog',dialog=>dialog.accept());
  await page.locator('#uploadDashboard').setInputFiles(await downloaded.path());
  await page.waitForFunction(()=>document.getElementById('dashboardStatus').textContent.includes('Dashboard restored'));
  // Named designs include a real dashboard snapshot and restore it with the workspace.
  const blocks=await context.newPage();await blocks.goto(origin+'/blocks/');
  await blocks.waitForFunction(()=>typeof NamedDesigns!=='undefined' && typeof workspace!=='undefined');
  await blocks.locator('#designName').fill('Dashboard roundtrip');
  await blocks.evaluate(()=>NamedDesigns.save());
  const listing=await blocks.request.get(origin+'/blocks/designs.php?action=list').then(r=>r.json());
  assert(listing.designs.some(item=>item.name==='Dashboard roundtrip'));
  const design=await blocks.request.get(origin+'/blocks/designs.php?action=load&name=Dashboard%20roundtrip').then(r=>r.json());
  assert.equal(design.workspace.codynick_dashboard.cards.length,13);
  blocks.on('dialog',dialog=>dialog.accept());
  await blocks.evaluate(()=>NamedDesigns.open());
  await blocks.locator('#designList').selectOption('Dashboard roundtrip');
  await blocks.evaluate(()=>NamedDesigns.load());
  assert.equal(await blocks.locator('#designName').inputValue(),'Dashboard roundtrip');
  await blocks.close();
  const touchContext=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
  const touch=await touchContext.newPage();await touch.goto(url);await touch.waitForSelector('.card');
  const touchButton=touch.getByRole('button',{name:'Hold',exact:true});await touchButton.scrollIntoViewIfNeeded();
  await touchButton.tap();await touch.waitForTimeout(300);
  assert.equal(await touchButton.getAttribute('aria-pressed'),'false','Touch tap must release');
  await touchContext.close();
  // Narrow layouts remain within the viewport and saved desktop sizes survive.
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(400);
  assert(await page.evaluate(()=>[...document.querySelectorAll('.card')].every(e=>e.getBoundingClientRect().right<=innerWidth+1)));
  await page.setViewportSize({width:1440,height:1000});await page.waitForTimeout(200);
  if(process.env.DASHBOARD_SCREENSHOT)await page.screenshot({path:process.env.DASHBOARD_SCREENSHOT,fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: Chrome polling stability, drag/keyboard move/resize, saved/shared layout, numeric slider, pointer/keyboard hold, legacy latch, export and responsive bounds');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
